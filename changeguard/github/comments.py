"""Post the ChangeGuard report as a single, updatable pull request comment."""
from __future__ import annotations

import json
from typing import Any
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

from changeguard.github.models import PullRequestRef

MARKER = "<!-- changeguard-report -->"
MAX_COMMENT_CHARS = 60_000  # GitHub limit is 65,536
_API = "https://api.github.com"


class CommentError(RuntimeError):
    pass


def post_report_comment(reference: PullRequestRef, report: str, token: str | None, *, opener=urlopen) -> str:
    """Create or update the ChangeGuard comment on ``reference``; returns the comment URL."""
    if not token:
        raise CommentError("Posting a comment needs a GitHub token (GITHUB_TOKEN or `gh auth login`).")
    body = _comment_body(report)
    base = f"/repos/{reference.owner}/{reference.repository}/issues"
    existing = _find_existing(f"{base}/{reference.number}/comments", token, opener)
    if existing is not None:
        result = _call("PATCH", f"{base}/comments/{existing}", token, opener, {"body": body})
    else:
        result = _call("POST", f"{base}/{reference.number}/comments", token, opener, {"body": body})
    return str(result.get("html_url", ""))


def _comment_body(report: str) -> str:
    if len(report) > MAX_COMMENT_CHARS:
        report = report[:MAX_COMMENT_CHARS] + "\n\n…report truncated; run `changeguard pr analyze` locally for the full version.\n"
    footer = "\n<sub>Generated by ChangeGuard. This comment updates on every push.</sub>\n"
    return f"{MARKER}\n{report.rstrip()}\n{footer}"


def _find_existing(path: str, token: str, opener) -> int | None:
    for page in range(1, 6):
        comments = _call("GET", f"{path}?per_page=100&page={page}", token, opener)
        if not isinstance(comments, list):
            return None
        for comment in comments:
            if isinstance(comment, dict) and MARKER in str(comment.get("body", "")):
                return int(comment["id"])
        if len(comments) < 100:
            return None
    return None


def _call(method: str, path: str, token: str, opener, payload: dict[str, Any] | None = None) -> Any:
    request = Request(
        _API + path,
        data=json.dumps(payload).encode() if payload is not None else None,
        method=method,
        headers={
            "Accept": "application/vnd.github+json",
            "Authorization": f"Bearer {token}",
            "User-Agent": "ChangeGuard",
            "X-GitHub-Api-Version": "2022-11-28",
            **({"Content-Type": "application/json"} if payload is not None else {}),
        },
    )
    try:
        with opener(request, timeout=30) as response:
            return json.loads(response.read().decode() or "null")
    except HTTPError as error:
        hint = " (the token needs pull-requests: write / issues: write)" if error.code in {401, 403, 404} else ""
        raise CommentError(f"GitHub API {method} failed: HTTP {error.code}{hint}") from error
    except (URLError, TimeoutError, ValueError) as error:
        raise CommentError(f"GitHub API {method} failed: {error}") from error
